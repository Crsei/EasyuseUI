export function matchesDictionaryEntry(entry: DictionaryEntry, query: string) {
  const normalize = (value: string) =>
    value
      .normalize("NFKC")
      .toLocaleLowerCase()
      .replace(/[\s_–—/-]+/g, "")
  const haystack = normalize(
    [
      entry.name,
      entry.chinese,
      entry.slug,
      ...(entry.aliases ?? []),
      entry.description,
    ].join(" "),
  )
  return query
    .trim()
    .split(/\s+/)
    .every((word) => haystack.includes(normalize(word)))
}
